import { useEffect, useMemo, useState } from 'react'
import { aiMatchEnabled, fetchAiMatch, type AiMatch, type Status } from '../../hooks/aiMatch'
import { matchJob } from '../../hooks/jobMatch'
import { useGraphStore } from '../../hooks/useGraphStore'
import { useView } from '../../hooks/useView'
import { body, card, muted, primaryButton, secondaryButton, strong, textLink } from './ui'

const MIN_AI_CHARS = 150

const STATUS = {
  match: {
    icon: '✓',
    label: 'matched',
    className:
      'border-emerald-500/40 bg-emerald-100 text-emerald-900 dark:border-emerald-400/40 dark:bg-emerald-400/10 dark:text-emerald-300',
  },
  partial: {
    icon: '◐',
    label: 'partial',
    className:
      'border-amber-500/40 bg-amber-100 text-amber-900 dark:border-amber-400/40 dark:bg-amber-400/10 dark:text-amber-300',
  },
  gap: {
    icon: '–',
    label: 'not shown on profile',
    className:
      'border-slate-300 bg-slate-100 text-slate-600 dark:border-slate-700 dark:bg-slate-800/60 dark:text-slate-400',
  },
} satisfies Record<Status, { icon: string; label: string; className: string }>

function AiResult({ ai }: { ai: AiMatch }) {
  const count = (s: Status) => ai.requirements.filter((r) => r.status === s).length
  return (
    <div className="mt-5 rounded-xl border border-violet-400/30 bg-violet-50 p-4 dark:bg-violet-400/[0.06]">
      <h4 className={`text-xs font-semibold uppercase tracking-wider text-violet-700 dark:text-violet-300`}>
        ✨ AI analysis
      </h4>
      <p className={`mt-2 text-sm leading-relaxed ${body}`}>{ai.summary}</p>
      <p className={`mt-3 text-sm font-semibold ${strong}`}>
        {(['match', 'partial', 'gap'] as const)
          .filter((s) => count(s) > 0)
          .map((s) => `${count(s)} ${STATUS[s].label}`)
          .join(' · ')}
      </p>
      <ul className="mt-3 space-y-2.5">
        {ai.requirements.map((r) => (
          <li key={r.requirement} className="flex gap-2.5 text-sm">
            <span
              className={`mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center rounded-full border text-xs font-bold ${STATUS[r.status].className}`}
              aria-label={STATUS[r.status].label}
            >
              {STATUS[r.status].icon}
            </span>
            <div>
              <span className={`font-semibold ${strong}`}>{r.requirement}</span>
              <span className={muted}> — {r.evidence}</span>
              {r.refs.length > 0 && (
                <span className="mt-1 flex flex-wrap gap-1.5">
                  {r.refs.map((n) =>
                    n.type === 'project' ? (
                      <a
                        key={n.id}
                        href={`#project-${n.id}`}
                        className="rounded-full border border-sky-500/40 px-2 py-0.5 text-[11px] text-sky-700 hover:bg-sky-50 dark:text-sky-300 dark:hover:bg-sky-400/10"
                      >
                        {n.label}
                      </a>
                    ) : (
                      <span
                        key={n.id}
                        className="rounded-full border border-slate-300 px-2 py-0.5 text-[11px] text-slate-600 dark:border-slate-700 dark:text-slate-400"
                      >
                        {n.label}
                      </span>
                    ),
                  )}
                </span>
              )}
            </div>
          </li>
        ))}
      </ul>
      {ai.topProjects.length > 0 && (
        <>
          <h4 className={`mt-4 text-xs font-semibold uppercase tracking-wider ${muted}`}>
            Most relevant projects
          </h4>
          <ul className={`mt-2 space-y-1.5 text-sm ${body}`}>
            {ai.topProjects.map(({ project, reason }) => (
              <li key={project.id}>
                <a href={`#project-${project.id}`} className={`font-semibold ${textLink}`}>
                  {project.label}
                </a>
                <span className={muted}> — {reason}</span>
              </li>
            ))}
          </ul>
        </>
      )}
      <p className={`mt-4 text-xs ${muted}`}>
        Generated by Google Gemini using only the facts on this page. It can make
        mistakes. The job description is sent to Google's API and isn't stored here.
      </p>
    </div>
  )
}

// Paste a job description, see which of the listed skills it mentions and
// the projects that show them
export default function JobMatch() {
  const [text, setText] = useState('')
  const result = useMemo(() => (text.trim() ? matchJob(text) : null), [text])
  const [aiEnabled, setAiEnabled] = useState(false)
  const [ai, setAi] = useState<AiMatch | null>(null)
  const [aiLoading, setAiLoading] = useState(false)
  const [aiError, setAiError] = useState('')

  // The AI button only appears when the site has a Gemini key configured
  useEffect(() => {
    aiMatchEnabled().then(setAiEnabled)
  }, [])

  const onTextChange = (value: string) => {
    setText(value)
    setAi(null)
    setAiError('')
  }

  const runAi = async () => {
    setAiLoading(true)
    setAiError('')
    try {
      setAi(await fetchAiMatch(text.trim()))
    } catch (e) {
      setAiError(e instanceof Error ? e.message : 'The AI service is unavailable right now.')
    } finally {
      setAiLoading(false)
    }
  }

  const showInGraph = () => {
    const ids = ai
      ? [
          ...ai.requirements.filter((r) => r.status !== 'gap').flatMap((r) => r.refs),
          ...ai.topProjects.map((p) => p.project),
        ].map((n) => n.id)
      : result
        ? [...result.skills, ...result.evidence.map((e) => e.project)].map((n) => n.id)
        : []
    if (ids.length === 0) return
    useGraphStore.getState().setFilter({
      kind: 'ids',
      label: ai ? 'AI job match' : 'Job description match',
      ids: [...new Set(ids)],
    })
    useView.getState().setView('graph')
  }

  return (
    <div id="match" className={`${card} scroll-mt-20`}>
      <h3 className={`text-lg font-semibold ${strong}`}>Hiring for a role?</h3>
      <p className={`mt-1 text-sm ${muted}`}>
        Paste the job description to see which of my skills it mentions and the
        projects where I've used them{aiEnabled ? ', or get an AI analysis of the fit' : ''}.
      </p>
      <label htmlFor="jd" className="sr-only">
        Job description
      </label>
      <textarea
        id="jd"
        value={text}
        onChange={(e) => onTextChange(e.target.value)}
        rows={5}
        placeholder="e.g. We're looking for a Data Scientist with Python, RAG, LangChain and Docker experience…"
        className="mt-4 w-full resize-y rounded-xl border border-slate-300 bg-slate-50 p-3 text-sm text-slate-900 placeholder:text-slate-400 focus:border-sky-500 focus:outline-none dark:border-slate-700 dark:bg-slate-950/60 dark:text-slate-100 dark:placeholder:text-slate-500"
      />
      <p className={`mt-1 text-xs ${muted}`}>
        The instant keyword match runs in your browser, and nothing is sent
        anywhere. It only knows the skills listed on this page.
      </p>

      {aiEnabled && (
        <div className="mt-3 flex flex-wrap items-center gap-3">
          <button
            type="button"
            onClick={runAi}
            disabled={aiLoading || text.trim().length < MIN_AI_CHARS}
            className={`cursor-pointer disabled:cursor-not-allowed disabled:opacity-50 ${primaryButton}`}
          >
            {aiLoading ? 'Analyzing… (about 10 seconds)' : '✨ Analyze fit with AI'}
          </button>
          {text.trim().length > 0 && text.trim().length < MIN_AI_CHARS && (
            <span className={`text-xs ${muted}`}>Paste the full job description for an AI analysis.</span>
          )}
        </div>
      )}
      {aiError && (
        <p className="mt-3 text-sm text-amber-800 dark:text-amber-300" role="status">
          {aiError} The keyword match below still works.
        </p>
      )}
      {ai && <AiResult ai={ai} />}

      {result && (
        <div className="mt-5" aria-live="polite">
          {ai && (
            <h4 className={`mb-3 text-xs font-semibold uppercase tracking-wider ${muted}`}>
              Keyword match
            </h4>
          )}
          {result.skills.length === 0 ? (
            <p className={`text-sm ${body}`}>
              No skills from my list found in this text. Try pasting the
              requirements section.
            </p>
          ) : (
            <>
              <p className={`text-sm font-semibold ${strong}`}>
                {result.skills.length} of my skills appear in this description
                {result.categories.length > 0 && (
                  <span className={`font-normal ${muted}`}>
                    {' '}
                    · also mentions {result.categories.map((c) => c.label).join(', ')}
                  </span>
                )}
              </p>
              <div className="mt-3 flex flex-wrap gap-2">
                {result.skills.map((s) => (
                  <span
                    key={s.id}
                    className="rounded-full border border-emerald-500/40 bg-emerald-100 px-3 py-1 text-xs font-medium text-emerald-900 dark:border-emerald-400/40 dark:bg-emerald-400/10 dark:text-emerald-300"
                  >
                    ✓ {s.label}
                  </span>
                ))}
              </div>
              {result.evidence.length > 0 && (
                <>
                  <h4 className={`mt-5 text-xs font-semibold uppercase tracking-wider ${muted}`}>
                    Where I've used them
                  </h4>
                  <ul className={`mt-2 space-y-1.5 text-sm ${body}`}>
                    {result.evidence.map(({ project, skills }) => (
                      <li key={project.id}>
                        <span className={`font-semibold ${strong}`}>{project.label}</span>
                        <span className={muted}> — {skills.map((s) => s.label).join(', ')}</span>
                      </li>
                    ))}
                  </ul>
                </>
              )}
              <div className="mt-5 flex flex-wrap items-center gap-3">
                <button type="button" onClick={showInGraph} className={`cursor-pointer ${secondaryButton}`}>
                  Highlight these in the 3D graph →
                </button>
                <button
                  type="button"
                  onClick={() => onTextChange('')}
                  className={`cursor-pointer text-sm ${textLink}`}
                >
                  Clear
                </button>
              </div>
            </>
          )}
        </div>
      )}
    </div>
  )
}
